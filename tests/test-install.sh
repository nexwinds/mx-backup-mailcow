#!/usr/bin/env bash
# Installer: bootstrap, idempotency, failures and local/offline installation.
set -uo pipefail
source "$(dirname "$0")/lib/helpers.sh"

sandbox_init
trap sandbox_destroy EXIT

API_KEY="0123456789abcdef0123456789abcdef"

RELEASE_DIR=$(prepare_release 9.9.9)
export MOCK_RELEASE_DIR="$RELEASE_DIR"
export MOCK_GH_LATEST="9.9.9"

install_args=(
    --non-interactive --skip-upgrade --no-firewall
    --mailcow-host mail.example.com
    --primary-ip 203.0.113.10
    --api-key-stdin
)

begin "install bootstraps the latest release and provisions the server"
run_with_stdin "$API_KEY" bash "$INSTALL" "${install_args[@]}"
assert_status 0 "install should succeed"
assert_file "$MXB_INSTALL_DIR/bin/sync-mailcow.sh" "sync script installed"
assert_file "$MXB_INSTALL_DIR/bin/update-scripts.sh" "updater installed"
assert_eq "$(cat "$MXB_INSTALL_DIR/VERSION")" "9.9.9" "release version installed"
assert_file "$MXB_CONFIG_FILE" "configuration written"
assert_mode "$MXB_CONFIG_FILE" "600" "configuration must be private"
assert_contains "$(cat "$MXB_CONFIG_FILE")" "MAILCOW_HOST=mail.example.com" "host stored"
assert_contains "$(cat "$MXB_CONFIG_FILE")" "$API_KEY" "API key stored"
assert_file "$MXB_SYSTEMD_DIR/mailcow-sync.timer" "timer unit installed"
assert_file "$MXB_SYSTEMD_DIR/mailcow-sync.service" "service unit installed"
assert_eq "$(mock_get_unit_state mailcow-sync.timer)" "active" "timer must be started"
assert_file "$MXB_LOGROTATE_DIR/mailcow-backup-mx" "log rotation installed"
assert_file "$MXB_POSTFIX_ETC/main.cf" "Postfix main.cf restored from the package template"
assert_file "$MXB_POSTFIX_ETC/master.cf" "Postfix master.cf restored from the package template"
assert_file "$MXB_MAPS_DIR/relay_domains.db" "maps generated by the initial sync"
assert_contains "$(cat "$MXB_MAPS_DIR/relay_domains")" "example.com" "relay domains synchronized"
assert_eq "$(json_get "$MXB_STATE_DIR/state/sync-state.json" '.status')" "ok" "initial sync status"
assert_called=$(mock_calls_count "apt-get -y -o Dpkg::Options::=--force-confold -o Dpkg::Options::=--force-confdef install postfix")
assert_eq "$assert_called" "1" "Postfix must be installed exactly once"
assert_contains "$(cat "$MXB_LOG_DIR/install.log")" "Mailcow API reachable" "API verified during install"

begin "installed application tree matches its checksum manifest"
assert_file "$MXB_INSTALL_DIR/systemd/mailcow-sync.service" "service unit included in the application tree"
assert_file "$MXB_INSTALL_DIR/systemd/mailcow-sync.timer" "timer unit included in the application tree"
assert_file "$MXB_INSTALL_DIR/logrotate/mailcow-backup-mx" "logrotate configuration included in the application tree"
run bash -c 'cd "$1" && sha256sum -c SHA256SUMS --quiet' _ "$MXB_INSTALL_DIR"
assert_status 0 "the installed application tree must match SHA256SUMS"

begin "installed commands report the release version from any path"
bare="$TEST_TMP/bare"
mkdir -p "$bare"
cp "$MXB_INSTALL_DIR/bin/sync-mailcow.sh" \
    "$MXB_INSTALL_DIR/bin/update.sh" \
    "$MXB_INSTALL_DIR/bin/diagnose.sh" \
    "$MXB_INSTALL_DIR/bin/update-scripts.sh" "$bare/"
for pair in \
    "sync-mailcow.sh:sync-mailcow" \
    "update.sh:update" \
    "diagnose.sh:diagnose" \
    "update-scripts.sh:update-scripts"; do
    run bash "$bare/${pair%%:*}" --version
    assert_status 0 "${pair%%:*} --version should succeed"
    assert_contains "$LAST_OUTPUT" "${pair##*:} 9.9.9" "${pair%%:*} must resolve VERSION"
done
run bash "$MXB_INSTALL_DIR/bin/install.sh" --version
assert_status 0 "installed installer --version should succeed"
assert_contains "$LAST_OUTPUT" "install 9.9.9" "installed installer must resolve VERSION"

begin "second run is idempotent and preserves configuration"
printf '\nCUSTOM_OPTION="keep-me"\n' >>"$MXB_CONFIG_FILE"
mock_clear_calls
run_with_stdin "" bash "$INSTALL" \
    --non-interactive --skip-upgrade --no-firewall \
    --mailcow-host mail.example.com \
    --primary-ip 203.0.113.10
assert_status 0 "second install should succeed"
assert_contains "$(cat "$MXB_CONFIG_FILE")" 'CUSTOM_OPTION="keep-me"' "unknown configuration lines preserved"
assert_contains "$(cat "$MXB_CONFIG_FILE")" "$API_KEY" "existing API key preserved"
assert_file "$MXB_MAPS_DIR/relay_domains" "maps still present"
assert_contains "$(cat "$MXB_LOG_DIR/sync.log")" "maps are unchanged" "unchanged maps skip the reload"

begin "an unconfigured postfix package is repaired before configuration"
sandbox_destroy
sandbox_init
RELEASE_DIR=$(prepare_release 9.9.9)
export MOCK_RELEASE_DIR="$RELEASE_DIR"
export MOCK_GH_LATEST="9.9.9"
export MOCK_POSTCONF_UNCONFIGURED=1
run_with_stdin "$API_KEY" bash "$INSTALL" "${install_args[@]}" --skip-initial-sync
assert_status 0 "install must succeed when postfix ships without main.cf"
assert_file "$MXB_POSTFIX_ETC/main.cf" "main.cf created from the package template"
assert_file "$MXB_POSTFIX_ETC/master.cf" "master.cf created from the package template"
assert_contains "$(cat "$MXB_LOG_DIR/install.log")" "restored" "template restoration is logged"
assert_eq "$(mock_calls_count 'postconf -e compatibility_level = 3.6')" "1" "a usable compatibility level is written"
assert_eq "$(mock_calls_count 'postconf -e compatibility_level = 0')" "0" "the built-in default 0 is never written"
export MOCK_POSTCONF_UNCONFIGURED=0

begin "compatibility level falls back to 3.6 when postfix reports 0"
sandbox_destroy
sandbox_init
RELEASE_DIR=$(prepare_release 9.9.9)
export MOCK_RELEASE_DIR="$RELEASE_DIR"
export MOCK_GH_LATEST="9.9.9"
cat >"$MXB_POSTFIX_TEMPLATE_DIR/main.cf.debian" <<'EOF'
# Postfix package template (test fixture, no compatibility level)
smtpd_banner = $myhostname ESMTP $mail_name (Ubuntu)
EOF
awk '!/^compatibility_level = /' "$MOCK_DIR/postconf.state" >"$MOCK_DIR/postconf.state.tmp"
mv "$MOCK_DIR/postconf.state.tmp" "$MOCK_DIR/postconf.state"
export MOCK_POSTCONF_COMPAT=0
run_with_stdin "$API_KEY" bash "$INSTALL" "${install_args[@]}" --skip-initial-sync
assert_status 0 "install must succeed when postfix reports compatibility level 0"
assert_eq "$(mock_calls_count 'postconf -e compatibility_level = 3.6')" "1" "the fallback must be 3.6"
export MOCK_POSTCONF_COMPAT=3.6

begin "a failed postfix start aborts with an actionable message"
sandbox_destroy
sandbox_init
RELEASE_DIR=$(prepare_release 9.9.9)
export MOCK_RELEASE_DIR="$RELEASE_DIR"
export MOCK_GH_LATEST="9.9.9"
export MOCK_SYSTEMCTL_START_FAIL=postfix
run_with_stdin "$API_KEY" bash "$INSTALL" "${install_args[@]}" --skip-initial-sync
assert_status 1 "install must fail when postfix does not start"
assert_contains "$LAST_OUTPUT" "Postfix did not start; inspect: journalctl -u postfix" "the startup failure must be actionable"
export MOCK_SYSTEMCTL_START_FAIL=""

begin "initial sync failure keeps the system installed and the timer enabled"
sandbox_destroy
sandbox_init
RELEASE_DIR=$(prepare_release 9.9.9)
export MOCK_RELEASE_DIR="$RELEASE_DIR"
export MOCK_GH_LATEST="9.9.9"
MOCK_API_BAD_JSON=1
run_with_stdin "$API_KEY" bash "$INSTALL" "${install_args[@]}"
assert_status 1 "install must fail when the initial sync fails"
assert_file "$MXB_INSTALL_DIR/bin/sync-mailcow.sh" "application remains installed"
assert_eq "$(mock_get_unit_state mailcow-sync.timer)" "active" "timer remains enabled"
assert_contains "$LAST_OUTPUT" "timer will retry" "recovery instructions printed"
export MOCK_API_BAD_JSON=0

begin "checksum mismatch aborts before any system change"
sandbox_destroy
sandbox_init
RELEASE_DIR=$(prepare_release 9.9.9)
export MOCK_RELEASE_DIR="$RELEASE_DIR"
export MOCK_GH_LATEST="9.9.9"
MOCK_CORRUPT_ASSET=1
run_with_stdin "$API_KEY" bash "$INSTALL" "${install_args[@]}"
assert_status 1 "corrupted download must abort"
assert_no_file "$MXB_INSTALL_DIR/bin/sync-mailcow.sh" "nothing installed"
assert_contains "$LAST_OUTPUT" "checksum mismatch" "checksum error reported"
assert_eq "$(mock_calls_count 'apt-get install')" "0" "packages must not be installed before verification"
export MOCK_CORRUPT_ASSET=0

begin "local directory installation works offline"
sandbox_destroy
sandbox_init
mock_clear_calls
run_with_stdin "$API_KEY" bash "$INSTALL" \
    --non-interactive --skip-upgrade --no-firewall --local-dir "$REPO_ROOT" \
    --mailcow-host mail.example.com --primary-ip 203.0.113.10
assert_status 0 "local installation should succeed"
assert_eq "$(cat "$MXB_INSTALL_DIR/VERSION")" "$(cat "$REPO_ROOT/VERSION")" "local version installed"
assert_eq "$(mock_calls_count 'github.com')" "0" "no GitHub download in local mode"
assert_file "$MXB_MAPS_DIR/relay_recipients" "maps generated in local mode"

begin "punycode Mailcow hostnames are accepted"
sandbox_destroy
sandbox_init
run_with_stdin "$API_KEY" bash "$INSTALL" \
    --non-interactive --skip-upgrade --no-firewall --skip-initial-sync \
    --local-dir "$REPO_ROOT" --api-key-stdin \
    --mailcow-host mail.xn--p1ai --primary-ip 203.0.113.10
assert_status 0 "punycode Mailcow hostname should pass validation"
assert_contains "$(cat "$MXB_CONFIG_FILE")" "MAILCOW_HOST=mail.xn--p1ai" "punycode host stored"

begin "numeric TLD hostnames are rejected"
sandbox_destroy
sandbox_init
run bash "$INSTALL" \
    --non-interactive --skip-upgrade --no-firewall --skip-initial-sync \
    --local-dir "$REPO_ROOT" \
    --mailcow-host mail.123 --primary-ip 203.0.113.10
assert_status 1 "numeric TLD hostname must be rejected"
assert_contains "$LAST_OUTPUT" "not a valid hostname" "clear hostname error"

begin "unsupported operating system is refused"
sandbox_destroy
sandbox_init
printf 'ID=debian\nVERSION_ID="12"\n' >"$MXB_OS_RELEASE"
run_with_stdin "$API_KEY" bash "$INSTALL" "${install_args[@]}"
assert_status 1 "non-Ubuntu system must be refused"
assert_contains "$LAST_OUTPUT" "Ubuntu 24.04 LTS only" "clear OS error"

begin "non-interactive mode requires connection details"
sandbox_destroy
sandbox_init
rm -f "$MXB_CONFIG_FILE"
run bash "$INSTALL" --non-interactive --skip-upgrade --no-firewall
assert_status 1 "missing details must fail"
assert_contains "$LAST_OUTPUT" "MAILCOW_HOST is required" "missing host reported"

finish
